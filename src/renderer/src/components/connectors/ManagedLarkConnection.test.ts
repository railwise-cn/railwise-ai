// @vitest-environment happy-dom
import { act, createElement } from 'react'
import { createRoot, type Root } from 'react-dom/client'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import i18n from '../../i18n'
import { ManagedLarkConnection } from './ManagedLarkConnection'

const api = {
  diagnoseManagedTool: vi.fn(), installManagedTool: vi.fn(), beginManagedLarkLogin: vi.fn(),
  completeManagedLarkLogin: vi.fn(), beginManagedLarkAppSetup: vi.fn(), checkManagedLarkAppSetup: vi.fn(),
  cancelManagedLarkAppSetup: vi.fn(), openExternal: vi.fn(async () => undefined)
}
let root: Root; let container: HTMLDivElement
const authorizationExpiry = () => new Date(Date.now() + 600_000).toISOString()
async function click(label: string): Promise<void> {
  const button = [...container.querySelectorAll('button')].find(item => item.textContent === label)
  if (!button) throw new Error(`Missing button: ${label}`)
  await act(async () => { button.click(); await Promise.resolve(); await Promise.resolve() })
}
async function startWaitingAppSetup(): Promise<void> {
  api.diagnoseManagedTool.mockResolvedValue({ ok: true, status: { id: 'lark-cli', state: 'needs_login' } })
  api.beginManagedLarkLogin.mockResolvedValue({ ok: false, reason: 'app_configuration_required', message: 'App required' })
  api.beginManagedLarkAppSetup.mockResolvedValue({ ok: true, state: 'waiting', verificationUrl: 'https://open.feishu.cn/device?first', expiresAt: authorizationExpiry() })
  await act(async () => { root.render(createElement(ManagedLarkConnection)) })
  await click('连接飞书')
}
describe('shared official Lark connection panel', () => {
  beforeEach(async () => {
    vi.resetAllMocks()
    api.openExternal.mockResolvedValue(undefined)
    await i18n.changeLanguage('zh')
    Object.assign(globalThis, { IS_REACT_ACT_ENVIRONMENT: true })
    Object.assign(window, { workwise: api })
    container = document.createElement('div'); document.body.append(container); root = createRoot(container)
  })
  afterEach(async () => { await act(async () => root.unmount()); container.remove(); vi.useRealTimers() })
  it('does not touch accounts when the connector catalog is only viewed', async () => {
    await act(async () => { root.render(createElement(ManagedLarkConnection)) })
    expect(api.diagnoseManagedTool).not.toHaveBeenCalled()
    expect(api.beginManagedLarkLogin).not.toHaveBeenCalled()
    expect(api.beginManagedLarkAppSetup).not.toHaveBeenCalled()
  })
  it('passes the selected mail capability only after the user connects', async () => {
    api.diagnoseManagedTool.mockResolvedValue({ ok: true, status: { id: 'lark-cli', state: 'installed', installedVersion: '1.0.100' } })
    api.beginManagedLarkLogin.mockResolvedValue({ ok: true, verificationUrl: 'https://accounts.feishu.cn/device', expiresAt: authorizationExpiry() })
    await act(async () => { root.render(createElement(ManagedLarkConnection)) })
    const select = container.querySelector('select')!
    await act(async () => { select.value = 'mail'; select.dispatchEvent(new Event('change', { bubbles: true })) })
    expect(api.beginManagedLarkLogin).not.toHaveBeenCalled()
    await click('连接飞书')
    expect(api.beginManagedLarkLogin).toHaveBeenCalledWith({ capability: 'mail' })
    expect(api.installManagedTool).not.toHaveBeenCalled()
    expect(container.querySelector('svg')).not.toBeNull()
  })
  it('retains a companion Skill warning and repairs the same CLI version without starting login', async () => {
    api.diagnoseManagedTool.mockResolvedValue({ ok: true, status: { id: 'lark-cli', state: 'installed', installedVersion: '1.0.100', skillWarning: '配套技能缺少 25 项' } })
    api.installManagedTool.mockResolvedValue({ ok: true, status: { id: 'lark-cli', state: 'installed', installedVersion: '1.0.100' } })
    await act(async () => { root.render(createElement(ManagedLarkConnection)) })
    await click('检查连接状态')
    expect(container.textContent).toContain('配套技能缺少 25 项')
    await click('修复配套工具')
    expect(api.installManagedTool).toHaveBeenCalledExactlyOnceWith('lark-cli')
    expect(container.textContent).not.toContain('配套技能缺少 25 项')
    expect(api.beginManagedLarkLogin).not.toHaveBeenCalled()
    expect(api.beginManagedLarkAppSetup).not.toHaveBeenCalled()
  })
  it('connects through official install and app scan after an explicit connect click', async () => {
    api.diagnoseManagedTool.mockResolvedValue({ ok: true, status: { id: 'lark-cli', state: 'not_installed' } })
    api.installManagedTool.mockResolvedValue({ ok: true, status: { id: 'lark-cli', state: 'needs_login' } })
    api.beginManagedLarkLogin.mockResolvedValue({ ok: false, reason: 'app_configuration_required', message: 'App required' })
    api.beginManagedLarkAppSetup.mockResolvedValue({ ok: true, state: 'waiting', verificationUrl: 'https://accounts.feishu.cn/device?synthetic', expiresAt: authorizationExpiry() })
    await act(async () => { root.render(createElement(ManagedLarkConnection)) })
    await click('连接飞书')
    expect(api.installManagedTool).toHaveBeenCalledWith('lark-cli')
    expect(api.beginManagedLarkAppSetup).toHaveBeenCalledOnce()
    expect(api.openExternal).toHaveBeenCalledWith('https://accounts.feishu.cn/device?synthetic')
    expect(container.querySelector('svg')).not.toBeNull()
    expect(container.textContent).toContain('RailWise 不会替你确认平台权限')
    expect(container.querySelector('input')).toBeNull()
    await act(async () => { root.render(createElement(ManagedLarkConnection)) })
    expect(api.beginManagedLarkAppSetup).toHaveBeenCalledOnce()
  })
  it('starts autoConnect once only after the caller records an explicit connect action', async () => {
    api.diagnoseManagedTool.mockResolvedValue({ ok: true, status: { id: 'lark-cli', state: 'needs_login' } })
    api.beginManagedLarkLogin.mockResolvedValue({ ok: true, verificationUrl: 'https://accounts.feishu.cn/user-login', expiresAt: authorizationExpiry() })
    api.completeManagedLarkLogin.mockResolvedValue({ ok: true, status: { id: 'lark-cli', state: 'installed' } })
    const onChanged = vi.fn(async () => undefined)
    await act(async () => { root.render(createElement(ManagedLarkConnection, { autoConnect: true, onChanged })); await Promise.resolve(); await Promise.resolve() })
    expect(api.beginManagedLarkLogin).toHaveBeenCalledOnce()
    expect(container.textContent).not.toContain('请输入')
    expect(container.textContent).not.toContain('undefined')
    await click('我已完成授权，检查登录')
    expect(api.completeManagedLarkLogin).toHaveBeenCalledOnce()
    expect(onChanged).toHaveBeenCalledTimes(2)
    expect(container.textContent).toContain('连接不会自动执行')
  })
  it('removes an expired authorization and exposes a fresh connection action', async () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-11-11T00:00:00Z'))
    api.diagnoseManagedTool.mockResolvedValue({ ok: true, status: { id: 'lark-cli', state: 'needs_login' } })
    api.beginManagedLarkLogin.mockResolvedValue({ ok: true, verificationUrl: 'https://accounts.feishu.cn/user-login', expiresAt: authorizationExpiry() })
    await act(async () => { root.render(createElement(ManagedLarkConnection)) })
    await click('连接飞书')
    expect(container.textContent).toContain('我已完成授权，检查登录')
    await act(async () => { await vi.advanceTimersByTimeAsync(600_000) })
    expect(container.textContent).not.toContain('我已完成授权，检查登录')
    expect(container.textContent).toContain(i18n.t('common:managedLarkAuthorizationExpired'))
    const connect = [...container.querySelectorAll('button')].find(item => item.textContent === '连接飞书')
    expect(connect?.disabled).toBe(false)
    expect(api.completeManagedLarkLogin).not.toHaveBeenCalled()
  })

  it('expires the first application setup QR and restores explicit setup actions without requesting another flow', async () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-11-11T00:00:00Z'))
    await startWaitingAppSetup()
    expect(container.querySelector('svg')).not.toBeNull()
    await act(async () => { await vi.advanceTimersByTimeAsync(599_999) })
    expect(container.querySelector('svg')).not.toBeNull()
    await act(async () => { await vi.advanceTimersByTimeAsync(1) })
    expect(container.querySelector('svg')).toBeNull()
    expect(container.textContent).toContain(i18n.t('common:capabilityLarkApp_expired'))
    expect(container.textContent).not.toContain('我已完成应用配置，检查结果')
    for (const label of ['连接飞书', '配置飞书应用（官方扫码）']) {
      expect([...container.querySelectorAll('button')].find(button => button.textContent === label)?.disabled).toBe(false)
    }
    expect(container.querySelector('select')?.disabled).toBe(false)
    expect(api.beginManagedLarkAppSetup).toHaveBeenCalledOnce()
    expect(api.beginManagedLarkLogin).toHaveBeenCalledOnce()
    expect(api.openExternal).toHaveBeenCalledOnce()
    expect(api.checkManagedLarkAppSetup).not.toHaveBeenCalled()
    expect(api.cancelManagedLarkAppSetup).not.toHaveBeenCalled()
    expect(api.completeManagedLarkLogin).not.toHaveBeenCalled()
  })

  it('keeps a newly requested application setup alive past the cancelled flow deadline', async () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-11-11T00:00:00Z'))
    await startWaitingAppSetup()
    await act(async () => { await vi.advanceTimersByTimeAsync(300_000) })
    api.cancelManagedLarkAppSetup.mockResolvedValue({ ok: true, state: 'cancelled' })
    await click('取消应用配置')
    api.beginManagedLarkAppSetup.mockResolvedValueOnce({ ok: true, state: 'waiting', verificationUrl: 'https://open.feishu.cn/device?second', expiresAt: authorizationExpiry() })
    await click('配置飞书应用（官方扫码）')
    await act(async () => { await vi.advanceTimersByTimeAsync(300_000) })
    expect(container.querySelector('svg')).not.toBeNull()
    expect(container.textContent).toContain(i18n.t('common:capabilityLarkApp_waiting'))
    expect(container.textContent).not.toContain(i18n.t('common:capabilityLarkApp_expired'))
    expect(api.openExternal).toHaveBeenLastCalledWith('https://open.feishu.cn/device?second')
    expect(api.beginManagedLarkAppSetup).toHaveBeenCalledTimes(2)
    await act(async () => { await vi.advanceTimersByTimeAsync(300_000) })
    expect(container.querySelector('svg')).toBeNull()
    expect(container.textContent).toContain(i18n.t('common:capabilityLarkApp_expired'))
  })

  it('preserves cancellation when the old application setup timer would expire', async () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-11-11T00:00:00Z'))
    await startWaitingAppSetup()
    api.cancelManagedLarkAppSetup.mockResolvedValue({ ok: true, state: 'cancelled' })
    await click('取消应用配置')
    await act(async () => { await vi.advanceTimersByTimeAsync(600_000) })
    expect(container.querySelector('svg')).toBeNull()
    expect(container.textContent).toContain(i18n.t('common:capabilityLarkApp_cancelled'))
    expect(container.textContent).not.toContain(i18n.t('common:capabilityLarkApp_expired'))
    expect(api.cancelManagedLarkAppSetup).toHaveBeenCalledOnce()
    expect(api.beginManagedLarkAppSetup).toHaveBeenCalledOnce()
  })

  it('does not replace a verified application and its user login with the old setup expiry', async () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-11-11T00:00:00Z'))
    await startWaitingAppSetup()
    await act(async () => { await vi.advanceTimersByTimeAsync(300_000) })
    api.checkManagedLarkAppSetup.mockResolvedValue({ ok: true, state: 'configured' })
    api.beginManagedLarkLogin.mockResolvedValueOnce({ ok: true, verificationUrl: 'https://accounts.feishu.cn/user-login', expiresAt: authorizationExpiry() })
    await click('我已完成应用配置，检查结果')
    await act(async () => { await vi.advanceTimersByTimeAsync(300_000) })
    expect(container.textContent).toContain(i18n.t('common:capabilityLarkAppReady'))
    expect(container.textContent).not.toContain(i18n.t('common:capabilityLarkApp_expired'))
    expect(container.textContent).toContain('我已完成授权，检查登录')
    expect(api.beginManagedLarkAppSetup).toHaveBeenCalledOnce()
    expect(api.beginManagedLarkLogin).toHaveBeenCalledTimes(2)
    expect(api.completeManagedLarkLogin).not.toHaveBeenCalled()
  })

  it('continues to user authorization after the official first-use configuration is verified', async () => {
    api.diagnoseManagedTool.mockResolvedValue({ ok: true, status: { id: 'lark-cli', state: 'needs_login' } })
    api.beginManagedLarkLogin.mockResolvedValueOnce({ ok: false, reason: 'app_configuration_required', message: 'App required' })
      .mockResolvedValueOnce({ ok: true, verificationUrl: 'https://accounts.feishu.cn/user-login', expiresAt: authorizationExpiry() })
    api.beginManagedLarkAppSetup.mockResolvedValue({ ok: true, state: 'waiting', verificationUrl: 'https://open.feishu.cn/device', expiresAt: authorizationExpiry() })
    api.checkManagedLarkAppSetup.mockResolvedValue({ ok: true, state: 'configured' })
    await act(async () => { root.render(createElement(ManagedLarkConnection)) })
    await click('连接飞书')
    expect(container.textContent).not.toContain('安装 Lark CLI')
    await click('我已完成应用配置，检查结果')
    expect(api.beginManagedLarkLogin).toHaveBeenCalledTimes(2)
    expect(api.openExternal).toHaveBeenLastCalledWith('https://accounts.feishu.cn/user-login')
    expect(api.completeManagedLarkLogin).not.toHaveBeenCalled()
  })
})
